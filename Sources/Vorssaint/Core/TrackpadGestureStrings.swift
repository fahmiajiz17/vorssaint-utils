struct TrackpadGestureStrings {
    let pageTitle: String
    let hubDescription: String
    let panelCaption: String
    let manageButton: String
    let activeNow: String
    let noTrackpad: String
    let appSwipeSection: String
    let appSwipeToggle: String
    let appSwipeCaptionFormat: String
    let fingersLabel: String
    let fingersThree: String
    let fingersFour: String
    let engageLabel: String
    let engageCaption: String
    let sensitivityLabel: String
    let stepCaption: String
    let exclusiveToggleFormat: String
    let exclusiveCaption: String
    let reversedToggle: String
    let reversedCaption: String
    let hapticsToggle: String
    let hapticsCaption: String
    let targetOwnSwitcher: String
    let targetSystemSwitcher: String
    let conflictThreeFingerDrag: String
    let conflictSystemSwipeFormat: String
    let openTrackpadSettings: String
    let openPointerSettings: String
    let edgeScrollSection: String
    let edgeScrollToggle: String
    let edgeScrollCaption: String
    let edgeZoneLabel: String
    let edgeZoneCaption: String
    let speedLabel: String
    let speedSlow: String
    let speedNormal: String
    let speedFast: String
    let acceleratesToggle: String
    let acceleratesCaption: String
    let horizontalToggle: String
    let switcherSwipeSection: String
    let switcherFollowToggle: String
    let switcherFollowCaption: String
    let switcherVerticalToggle: String
    let switcherVerticalCaption: String
    let staysInRowToggle: String
    let staysInRowCaption: String

    func appSwipeCaption(fingers: Int) -> String {
        String(format: appSwipeCaptionFormat, fingers)
    }

    func conflict(_ conflict: TrackpadSwipeConflict) -> String {
        switch conflict {
        case .threeFingerDrag: return conflictThreeFingerDrag
        case .systemSwipe(let fingers): return String(format: conflictSystemSwipeFormat, fingers)
        }
    }

    func name(_ fingers: TrackpadSwipeFingers) -> String {
        switch fingers {
        case .three: return fingersThree
        case .four: return fingersFour
        }
    }

    func exclusiveToggle(fingers: Int) -> String {
        String(format: exclusiveToggleFormat, fingers)
    }

    func name(_ speed: TrackpadEdgeScrollSpeed) -> String {
        switch speed {
        case .slow: return speedSlow
        case .normal: return speedNormal
        case .fast: return speedFast
        }
    }
}

extension FeatureStrings {
    static func trackpadGestures(_ language: AppLanguage) -> TrackpadGestureStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        case .uk: return .uk
        }
    }
}

